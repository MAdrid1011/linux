#include <linux/linkage.h>

#include <asm/asm.h>
#include <asm/csr.h>
#include <asm/asm-offsets.h>

#ifdef CONFIG_RISCV_ISA_F_ONLY
#define FSTATE_STORE fsw
#define FSTATE_LOAD flw
#else
#define FSTATE_STORE fsd
#define FSTATE_LOAD fld
#endif

ENTRY(__fstate_save)
	li  a2,  TASK_THREAD_F0
	add a0, a0, a2
	li t1, SR_FS
	csrs CSR_STATUS, t1
	frcsr t0
	FSTATE_STORE f0,  TASK_THREAD_F0_F0(a0)
	FSTATE_STORE f1,  TASK_THREAD_F1_F0(a0)
	FSTATE_STORE f2,  TASK_THREAD_F2_F0(a0)
